// Renders the chibi sprites headlessly into compact pixel strings for the
// Claude Code "buddy" mod (buddy/hooks/frames.ts). Run: npm run buddy:frames
import { writeFileSync } from 'node:fs';
import { ALL_ROLES, SPRITE_H, SPRITE_W, drawChibi, type Pose } from '../src/web/sprites.js';

export const BUDDY_POSES = ['idle', 'work', 'sleep'] as const satisfies readonly Pose[];
const KEYS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';

/** One sprite frame as SPRITE_W*SPRITE_H hex colours ('' = transparent). */
export function renderFrame(role: string, pose: Pose, frame: number): string[] {
  const px: string[] = new Array(SPRITE_W * SPRITE_H).fill('');
  let fill = '';
  const ctx = {
    set fillStyle(c: string) { fill = c; },
    get fillStyle() { return fill; },
    fillRect(x: number, y: number, w: number, h: number) {
      for (let j = y; j < y + h; j++) for (let i = x; i < x + w; i++) {
        if (i >= 0 && i < SPRITE_W && j >= 0 && j < SPRITE_H) px[j * SPRITE_W + i] = fill.toLowerCase();
      }
    },
  } as unknown as CanvasRenderingContext2D;
  drawChibi(ctx, 0, 0, role as never, pose, frame);
  return px;
}

/** The whole frames module's source: per role a palette and one frame (0) per pose. */
export function framesSource(): string {
  const roles: Record<string, { palette: string[]; poses: Record<string, string> }> = {};
  for (const role of ALL_ROLES) {
    const palette: string[] = [];
    const poses: Record<string, string> = {};
    for (const pose of BUDDY_POSES) {
      poses[pose] = renderFrame(role, pose, 0).map(c => {
        if (!c) return '.';
        let i = palette.indexOf(c);
        if (i < 0) { i = palette.length; palette.push(c); }
        if (i >= KEYS.length) throw new Error(`palette of ${role} too large`);
        return KEYS[i];
      }).join('');
    }
    roles[role] = { palette, poses };
  }
  return [
    '// Generated by scripts/buddy-frames.ts from src/web/sprites.ts. Do not edit.',
    `export const WIDTH = ${SPRITE_W};`,
    `export const HEIGHT = ${SPRITE_H};`,
    `export const KEYS = ${JSON.stringify(KEYS)};`,
    `export const POSES = ${JSON.stringify(BUDDY_POSES)} as const;`,
    'export type BuddyPose = (typeof POSES)[number];',
    `export const ROLES: Record<string, { palette: string[]; poses: Record<BuddyPose, string> }> = ${JSON.stringify(roles, null, 1)};`,
    '',
  ].join('\n');
}

if (process.argv[1]?.endsWith('buddy-frames.ts')) {
  writeFileSync(new URL('../buddy/hooks/frames.ts', import.meta.url), framesSource());
  console.log('wrote buddy/hooks/frames.ts');
}
